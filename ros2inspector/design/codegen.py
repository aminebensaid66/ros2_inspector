@dataclass
class EditPlan:
    """How to bring the user's edited files in line with the design, decided before writing."""

    moves: list[tuple[str, str]] = field(default_factory=list)
    patched: dict[str, str] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    problems: list[str] = field(default_factory=list)


def plan_package_edits(
    package: PackageSpec,
    read: Callable[[str], bytes | None],
    manifest: dict[str, str],
    previous_nodes: dict[str, str],
) -> EditPlan:
    """Decide what generation must change in files the user edited so the package still runs.

    Edited files are never regenerated, but some of their content is the design's: the module
    a node lives in, its ``console_scripts`` entry and the executables the launch file starts.
    An edited node module follows its node through a rename, an edited ``setup.py`` gets the
    missing entries appended to its list, and an edited launch file gets the renamed
    executables. Whatever cannot be done safely is a problem, so nothing is reported as
    generated while ``setup.py`` or the launch file points at code that is not there.
    ``read`` returns a file's current bytes (None if missing); ``manifest`` holds the hashes
    recorded at the last generation, under the package's current paths.
    """
    plan = EditPlan()
    pkg = package.pkg_name

    def edited(relative: str) -> bool:
        data = read(relative)
        return data is not None and _digest(data) != manifest.get(relative)

    def text_of(relative: str) -> str | None:
        data = read(relative)
        try:
            return None if data is None else data.decode("utf-8")
        except UnicodeDecodeError:
            return None

    labels = [node.label for node in package.nodes]
    renamed = {
        previous_nodes[node.id]: node.label
        for node in package.nodes
        if previous_nodes.get(node.id) not in (None, node.label)
    }
    for old, new in renamed.items():
        old_rel, new_rel = f"{pkg}/{old}.py", f"{pkg}/{new}.py"
        if not edited(old_rel):
            continue  # unedited: it is regenerated under the new name and the old one removed
        source = text_of(old_rel)
        if read(new_rel) is not None:
            reason = f"{new_rel} already exists"
            fix = f"Merge your code into {new_rel} and delete {old_rel}"
        elif old in labels:
            reason = f"another node is now named '{old}'"
            fix = f"Move your code to {new_rel} yourself"
        elif source is None:
            reason = "it is not UTF-8 text"
            fix = f"Move your code to {new_rel} yourself"
        else:
            reason = ""
        if reason:
            plan.problems.append(
                f"{old_rel} has your edits, but it cannot follow the renamed node because "
                f"{reason}. {fix}, or rename the node back to '{old}'."
            )
            continue
        assert source is not None
        spec = next(node for node in package.nodes if node.label == new)
        old_spec = spec.model_copy(update={"label": old})
        _, names = _import_plan(old_spec)
        try:
            updated = rename_constructor(
                source, old, new, node_class_name(old_spec, set(names.values()))
            )
        except ValueError as exc:
            plan.problems.append(
                f"{old_rel} has your edits; its constructor cannot be renamed safely: {exc}. "
                f"Please update the node name in the constructor yourself and move it to "
                f"{new_rel}, or rename the node back to '{old}'."
            )
            continue
        plan.moves.append((old_rel, new_rel))
        plan.patched[new_rel] = updated
        plan.notes.append(f"moved your edited {old_rel} to {new_rel}")

    entries = {label: f"{label} = {pkg}.{label}:main" for label in labels}
    registered: set[str] | None = set(labels)
    if edited("setup.py"):
        original = text_of("setup.py")
        setup_text = original or ""
        if renamed:
            try:
                setup_text = rename_script_entries(
                    setup_text,
                    {f"{old} = {pkg}.{old}:main": entries[new] for old, new in renamed.items()},
                )
            except ValueError as exc:
                plan.problems.append(
                    f"setup.py has your edits; update console_scripts by hand: {exc}."
                )
        changed = sorted(new for old, new in renamed.items() if repr(entries[new]) in setup_text)
        registered = console_scripts(setup_text) if original is not None else None
        missing = [
            entry
            for label, entry in entries.items()
            if registered is None or label not in registered
        ]
        if missing:
            added = add_console_scripts(setup_text, missing) if original is not None else None
            if added is None:
                plan.problems.append(
                    "setup.py has your edits and its console_scripts list could not be updated "
                    f"automatically. Add {', '.join(repr(e) for e in missing)} to it, or undo "
                    "your edits so it can be regenerated."
                )
            else:
                setup_text = added
                changed = sorted({*changed, *(e.split(" = ", 1)[0] for e in missing)})
            registered = console_scripts(setup_text)
        # A registered executable can still point at a missing or wrong module.
        # Check full targets, including duplicates, before accepting edited setup.py.
        targets = console_script_targets(setup_text) if original is not None else None
        if targets is not None:
            for label, entry in entries.items():
                expected = entry.partition("=")[2].strip()
                actual = targets.get(label, [])
                if actual and (len(actual) != 1 or actual[0] != expected):
                    plan.problems.append(
                        f"setup.py has your edits; console script {label!r} must point to "
                        f"{expected!r}, but registers {actual!r}. "
                        "Correct the registration before regenerating."
                    )
        if original is not None and setup_text != original:
            plan.patched["setup.py"] = setup_text
            plan.notes.append(f"registered {', '.join(changed)} in your edited setup.py")

    launch_rel = "launch/launch.py"
    if edited(launch_rel):
        original = text_of(launch_rel)
        launch_text = original or ""
        try:
            launch_text, started = rename_launch_nodes(launch_text, renamed, pkg)
        except ValueError as exc:
            plan.problems.append(
                f"{launch_rel} has your edits; update its Node entries by hand: {exc}."
            )
            started = set()
        known = set(labels) | set(previous_nodes.values())
        for executable in sorted(started & known):
            if registered is not None and executable not in registered:
                plan.problems.append(
                    f"{launch_rel} has your edits and starts '{executable}', which setup.py "
                    "does not register, so ros2 launch would fail. Update the launch file, or "
                    "undo your edits so it can be regenerated."
                )
        not_started = [label for label in labels if label not in started]
        if not_started:
            plan.warnings.append(
                f"{launch_rel} has your edits, so it does not start {', '.join(not_started)}; "
                "add the node(s) to it yourself."
            )
        if original is not None and launch_text != original:
            plan.patched[launch_rel] = launch_text
            plan.notes.append(f"renamed the node(s) in your edited {launch_rel}")

    if edited("package.xml"):
        declared = set(_DEPEND.findall(text_of("package.xml") or ""))
        missing_deps = [
            dep for dep in [*_dependencies(package), "launch", "launch_ros"] if dep not in declared
        ]
        if missing_deps:
            plan.warnings.append(
                "package.xml has your edits and does not declare "
                f"{', '.join(missing_deps)}; add <depend> entries for them."
            )
    return plan


def rename_package_contents(package_dir: Path, old_name: str, new_name: str) -> list[str]:
    """Move package paths and update only the metadata constructs that name the package."""
    if old_name == new_name:
        return []
    pending = package_name_edits(package_dir, old_name, new_name)
    renames = [(old_name, new_name), (f"resource/{old_name}", f"resource/{new_name}")]
    moved: list[tuple[str, str]] = []
    for old, new in renames:
        source, target = package_dir / old, package_dir / new
        if source.exists() and not target.exists():
            source.rename(target)
            moved.append((old, new))
    manifest = read_manifest(package_dir)
    if manifest is None:
        return []

    def moved_key(key: str) -> str:
        for old, new in moved:
            if key == old or key.startswith(f"{old}/"):
                return new + key[len(old) :]
        return key

    manifest = {moved_key(key): digest for key, digest in manifest.items()}
    rewritten = []
    for relative, data in pending.items():
        relative = moved_key(relative)
        _write_atomic(package_dir / relative, data)
        rewritten.append(relative)
    _write_marker(package_dir, manifest, previous_node_labels(package_dir))
    return rewritten


def rename_blockers(package_dir: Path, old_name: str, new_name: str) -> list[str]:
    """Paths inside a package that would stop its module folder from being renamed."""
    blockers = []
    for old, new in ((old_name, new_name), (f"resource/{old_name}", f"resource/{new_name}")):
        if (package_dir / old).exists() and (package_dir / new).exists():
            blockers.append(new)
    return blockers


_PACKAGE_NAME_FILES = frozenset({"setup.py", "setup.cfg", "package.xml"})


def _is_launch_file(relative: str) -> bool:
    parts = relative.split("/")
    return parts[0] == "launch" or ".launch." in parts[-1]


def package_name_edits(package_dir: Path, old_name: str, new_name: str) -> dict[str, bytes]:
    """Plan metadata changes completely before a package directory can move."""
    if old_name == new_name:
        return {}
    manifest = read_manifest(package_dir) or {}
    pending: dict[str, bytes] = {}
    for relative, digest in sorted(manifest.items()):
        if relative not in _PACKAGE_NAME_FILES and not _is_launch_file(relative):
            continue
        path = package_dir / relative
        if path.is_symlink() or not path.is_file():
            continue
        data = path.read_bytes()
        if _digest(data) == digest:
            continue
        try:
            source = data.decode("utf-8")
            updated = rename_package_text(relative, source, old_name, new_name)
        except (UnicodeDecodeError, ValueError) as exc:
            raise ValueError(
                f"{relative} has your edits; update its package references "
                f"by hand before renaming: {exc}."
            ) from exc
        if updated != source:
            pending[relative] = updated.encode("utf-8")
    return pending


def _write_atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = default_file_mode(path)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
            if hasattr(os, "fchmod"):
                os.fchmod(stream.fileno(), mode)
        if not hasattr(os, "fchmod"):
            os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def _inside(base: Path, relative: str) -> Path:
    path = (base / relative).resolve()
    if not path.is_relative_to(base.resolve()):
        raise ValueError(f"refusing to write outside the package: {relative}")
    return path


def write_package(
    package: PackageSpec,
    output_dir: Path,
    files: dict[str, str],
    previous_nodes: dict[str, str] | None = None,
) -> GenerateResult:
    """Write rendered files without ever overwriting user edits.

    A file is (re)written only when it does not exist yet, or when its current content still
    matches the hash recorded at the previous generation. Edited files are kept and reported,
    with only the changes ``plan_package_edits`` decides they need to keep the package
    runnable. Files the user added are never touched. Generated files that are no longer part
    of the design are removed only if unmodified. ``previous_nodes`` (node id -> name at the
    last generation) defaults to what the package marker recorded.
    """
    target = output_dir / package.pkg_name
    result = GenerateResult(package=package.pkg_name)
    manifest: dict[str, str] = {}
    if target.exists():
        previous = read_manifest(target)
        if previous is None:
            raise FileExistsError(
                f"Refusing to overwrite '{target}': it was not generated by ROS 2 Inspector."
            )
        manifest = previous
    if previous_nodes is None:
        previous_nodes = previous_node_labels(target)
    target.mkdir(parents=True, exist_ok=True)

    def read(relative: str) -> bytes | None:
        path = _inside(target, relative)
        return path.read_bytes() if path.is_file() else None

    plan = plan_package_edits(package, read, manifest, previous_nodes)
    if plan.problems:
        raise ValueError(" ".join(plan.problems))
    for old_rel, new_rel in plan.moves:
        _write_atomic(_inside(target, new_rel), plan.patched[new_rel].encode("utf-8"))
        _inside(target, old_rel).unlink()
        manifest[new_rel] = manifest.pop(old_rel, "")
    result.notes.extend(plan.notes)
    result.warnings.extend(plan.warnings)

    new_manifest: dict[str, str] = {}
    for relative, text in sorted(files.items()):
        data = text.encode("utf-8")
        new_hash = _digest(data)
        path = _inside(target, relative)
        if relative in plan.patched:
            # An edited file: keep the user's version with only the planned change, and keep
            # its old hash so it still counts as edited next time.
            if relative not in dict(plan.moves).values():
                _write_atomic(path, plan.patched[relative].encode("utf-8"))
            result.kept_modified.append(relative)
            if manifest.get(relative):
                new_manifest[relative] = manifest[relative]
            continue
        if path.exists():
            current_hash = _digest(path.read_bytes())
            if current_hash == new_hash:
                result.unchanged.append(relative)
                new_manifest[relative] = new_hash
                continue
            if manifest.get(relative) != current_hash:
                # Edited (or pre-existing and unknown): keep the user's version.
                result.kept_modified.append(relative)
                if relative in manifest:
                    new_manifest[relative] = manifest[relative]
                continue
        _write_atomic(path, data)
        result.written.append(relative)
        new_manifest[relative] = new_hash

    for relative, old_hash in sorted(manifest.items()):
        if relative in files:
            continue
        path = _inside(target, relative)
        if not path.exists():
            continue
        if _digest(path.read_bytes()) == old_hash:
            path.unlink()
            result.removed.append(relative)
        else:
            result.kept_modified.append(relative)

    _write_marker(target, new_manifest, {node.id: node.label for node in package.nodes})
    return result


def generate_package_result(
    payload: dict[str, Any] | PackageSpec, output_dir: Path
) -> GenerateResult:
    """Validate, render and write one package; report what changed on disk."""
    package = payload if isinstance(payload, PackageSpec) else PackageSpec.model_validate(payload)
    output_dir = output_dir.expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    files = render_package(package)
    return write_package(package, output_dir, files)


def generate_package(payload: dict[str, Any] | PackageSpec, output_dir: Path) -> list[str]:
    """Generate a package and return the paths (relative to ``output_dir``) that match the design.

    Existing directories are updated only when they contain the generator marker, and only
    files that the user has not modified since the last generation are replaced.
    """
    result = generate_package_result(payload, output_dir)
    return sorted(f"{result.package}/{path}" for path in result.written + result.unchanged)
