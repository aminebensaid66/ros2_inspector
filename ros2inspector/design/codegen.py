def render_package(package: PackageSpec) -> dict[str, str]:
    """Render every generated file of a package, keyed by POSIX path relative to it.

    Python sources are compiled before anything is written, so a template bug can never
    leave a half-written package behind.
    """
    files: dict[str, str] = {}
    for node in package.nodes:
        files[f"{package.pkg_name}/{node.label}.py"] = render_node(node)
    files[f"{package.pkg_name}/__init__.py"] = ""
    files[f"resource/{package.pkg_name}"] = ""
    files["package.xml"] = _render(
        _PKG_XML_TMPL,
        pkg_name=package.pkg_name,
        deps=_dependencies(package),
        exec_deps=["launch", "launch_ros"],
        test_deps=_TEST_DEPENDS,
    )
    entry_points = [
        repr(f"{node.label} = {package.pkg_name}.{node.label}:main") for node in package.nodes
    ]
    files["setup.py"] = _render(
        _SETUP_PY_TMPL, pkg_literal=repr(package.pkg_name), entry_points=entry_points
    )
    files["setup.cfg"] = _SETUP_CFG.format(pkg=package.pkg_name)
    files.update(_TEST_FILES)
    files["README.md"] = _render(
        _README_TMPL, pkg_name=package.pkg_name, nodes=[_readme_node(n) for n in package.nodes]
    )
    files["launch/launch.py"] = _render(
        _LAUNCH_TMPL,
        pkg_literal=repr(package.pkg_name),
        nodes=[{"literal": repr(node.label)} for node in package.nodes],
    )
    for relative, source in files.items():
        if relative.endswith(".py"):
            files[relative] = source = _fit_line_length(source)
            compile(source, relative, "exec")
    return files


def _read_marker(package_dir: Path) -> dict[str, Any] | None:
    marker = package_dir / _GENERATED_MARKER
    if not marker.is_file():
        return None
    try:
        data: object = json.loads(marker.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return {}
    return data if isinstance(data, dict) else {}


def read_manifest(package_dir: Path) -> dict[str, str] | None:
    """Return {relative path: sha256} recorded at the last generation.

    ``None`` means the directory is not a generated package. Legacy (format 1) markers have
    no hashes and return an empty manifest, so every existing file is treated as user-owned.
    """
    data = _read_marker(package_dir)
    if data is None:
        return None
    if not isinstance(data.get("files"), dict):
        return {}
    return {str(k): str(v) for k, v in data["files"].items()}


def previous_node_labels(package_dir: Path) -> dict[str, str]:
    """Node id -> node name at the last generation (empty for markers older than this)."""
    nodes = (_read_marker(package_dir) or {}).get("nodes")
    if not isinstance(nodes, dict):
        return {}
    return {str(k): str(v) for k, v in nodes.items()}


def _write_marker(package_dir: Path, files: dict[str, str], nodes: dict[str, str]) -> None:
    marker = {
        "generated_by": "ros2inspector",
        "format": _MARKER_FORMAT,
        "files": files,
        "nodes": nodes,
    }
    _write_atomic(
        package_dir / _GENERATED_MARKER,
        (json.dumps(marker, indent=2, sort_keys=True) + "\n").encode("utf-8"),
    )


def _console_scripts_list(tree: ast.AST) -> ast.List | None:
    """The literal ``'console_scripts': [...]`` list of a setup.py, if it has exactly one."""
    try:
        listing = console_script_list(tree)
    except ValueError:
        return None
    if not all(
        isinstance(item, ast.Constant) and isinstance(item.value, str) for item in listing.elts
    ):
        return None
    return listing


def console_scripts(setup_py: str) -> set[str] | None:
    """Executable names a setup.py registers, or None when they cannot be read statically."""
    try:
        listing = _console_scripts_list(ast.parse(setup_py))
    except SyntaxError:
        return None
    if listing is None:
        return None
    return {
        str(item.value).split("=", 1)[0].strip()
        for item in listing.elts
        if isinstance(item, ast.Constant)
    }


def console_script_targets(setup_py: str) -> dict[str, list[str]] | None:
    """Return every executable target in a statically readable setup.py registration."""
    try:
        listing = _console_scripts_list(ast.parse(setup_py))
    except SyntaxError:
        return None
    if listing is None:
        return None
    targets: dict[str, list[str]] = {}
    for item in listing.elts:
        assert isinstance(item, ast.Constant) and isinstance(item.value, str)
        executable, separator, target = item.value.partition("=")
        if not separator or not executable.strip() or not target.strip():
            return None
        targets.setdefault(executable.strip(), []).append(target.strip())
    return targets


def add_console_scripts(setup_py: str, entries: list[str]) -> str | None:
    """Insert entries at the end of setup.py's console_scripts list, leaving the rest as is.

    Returns None when the list cannot be located safely, so the caller can ask the user to
    add the entries by hand instead of guessing.
    """
    try:
        listing = _console_scripts_list(ast.parse(setup_py))
    except SyntaxError:
        return None
    if listing is None or listing.end_lineno is None or listing.end_col_offset is None:
        return None
    lines = setup_py.splitlines(keepends=True)

    def offset(line: int, column: int) -> int:
        # ast columns count UTF-8 bytes.
        prefix = lines[line - 1].encode("utf-8")[:column].decode("utf-8")
        return sum(len(text) for text in lines[: line - 1]) + len(prefix)

    if listing.elts:
        last = listing.elts[-1]
        assert last.end_lineno is not None and last.end_col_offset is not None
        position = offset(last.end_lineno, last.end_col_offset)
        indent = re.match(r"[ \t]*", lines[last.lineno - 1]).group(0)  # type: ignore[union-attr]
        rest = setup_py[position:]
        comma = rest.lstrip(" \t").startswith(",")
        after = position + len(rest) - len(rest.lstrip(" \t")) + 1 if comma else position
        line_end = setup_py.find("\n", after)
        tail = setup_py[after : line_end if line_end >= 0 else len(setup_py)].strip()
        if line_end >= 0 and (not tail or tail.startswith("#")):
            # One entry per line: new lines go after the last entry's line (and its comment).
            lines_text = "".join(f"{indent}{entry!r},\n" for entry in entries)
            updated = setup_py[: line_end + 1] + lines_text + setup_py[line_end + 1 :]
            if not comma:
                updated = updated[:position] + "," + updated[position:]
        elif comma:
            updated = setup_py[:after] + "".join(f" {e!r}," for e in entries) + setup_py[after:]
        else:
            joined = "".join(f", {entry!r}" for entry in entries)
            updated = setup_py[:position] + joined + setup_py[position:]
    else:
        position = offset(listing.end_lineno, listing.end_col_offset) - 1
        outer = re.match(r"[ \t]*", lines[listing.lineno - 1]).group(0)  # type: ignore[union-attr]
        text = "".join(f"\n{outer}    {entry!r}," for entry in entries) + f"\n{outer}"
        updated = setup_py[:position] + text + setup_py[position:]
    names = console_scripts(updated)
    wanted = {entry.split("=", 1)[0].strip() for entry in entries}
    return updated if names is not None and wanted <= names else None


