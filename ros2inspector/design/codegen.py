_env = Environment(
    autoescape=False,
    keep_trailing_newline=True,
    undefined=StrictUndefined,
)

# Names every generated node module binds besides its interface imports.
_MODULE_NAMES = frozenset({"rclpy", "Node", "ActionClient", "ActionServer", "main"})


@dataclass
class GenerateResult:
    """Outcome of generating one package."""

    package: str
    written: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    kept_modified: list[str] = field(default_factory=list)
    removed: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "package": self.package,
            "written": self.written,
            "unchanged": self.unchanged,
            "kept_modified": self.kept_modified,
            "removed": self.removed,
        }


def _pascal(value: str) -> str:
    return "".join(part.capitalize() for part in value.split("_"))


def _render(template: str, **context: Any) -> str:
    return _env.from_string(template).render(**context)


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


_KIND_GROUPS: tuple[tuple[str, InterfaceKind], ...] = (
    ("publishers", "msg"),
    ("subscribers", "msg"),
    ("services", "srv"),
    ("clients", "srv"),
    ("action_servers", "action"),
    ("action_clients", "action"),
)


def _interfaces(node: NodeSpec) -> set[tuple[str, InterfaceKind, str]]:
    found: set[tuple[str, InterfaceKind, str]] = set()
    for group, kind in _KIND_GROUPS:
        for endpoint in getattr(node, group):
            package, _, type_name = split_interface(endpoint.interface_type)
            found.add((package, kind, type_name))
    return found


def _import_plan(node: NodeSpec) -> tuple[list[str], dict[tuple[str, str, str], str]]:
    """Return import lines and the local name for each (package, kind, Type).

    Plain ``from pkg.msg import Type`` is used unless two interfaces share a type name,
    in which case each gets a package-qualified alias (``StdMsgsString``).
    """
    interfaces = sorted(_interfaces(node))
    counts: dict[str, int] = {}
    for _, _, type_name in interfaces:
        counts[type_name] = counts.get(type_name, 0) + 1
    names: dict[tuple[str, str, str], str] = {}
    lines: list[str] = []
    for package, kind, type_name in interfaces:
        if counts[type_name] > 1 or type_name in _MODULE_NAMES:
            local = _pascal(package) + ("" if kind == "msg" else _pascal(kind)) + type_name
            lines.append(f"from {package}.{kind} import {type_name} as {local}")
        else:
            local = type_name
            lines.append(f"from {package}.{kind} import {type_name}")
        names[(package, kind, type_name)] = local
    return lines, names


def node_class_name(node: NodeSpec, imported: set[str]) -> str:
    """Class name for a node that never shadows an imported interface or rclpy name."""
    cls = _pascal(node.label)
    if cls in imported or cls in _MODULE_NAMES:
        cls = f"{cls}Node"
    while cls in imported or cls in _MODULE_NAMES:
        cls = f"{cls}_"
    return cls


def _prepare_endpoints(
    endpoints: list[EndpointSpec],
    kind: InterfaceKind,
    names: dict[tuple[str, str, str], str],
) -> list[dict[str, str]]:
    prepared: list[dict[str, str]] = []
    used_vars: set[str] = set()
    for index, endpoint in enumerate(endpoints, start=1):
        base = endpoint.name.lstrip("~").strip("/").replace("/", "_") or f"endpoint_{index}"
        var = base
        suffix = 2
        while var in used_vars:
            var = f"{base}_{suffix}"
            suffix += 1
        used_vars.add(var)
        package, _, type_name = split_interface(endpoint.interface_type)
        prepared.append(
            {
                "var": var,
                "cls": names[(package, kind, type_name)],
                "name_literal": repr(endpoint.name),
                "received_literal": repr(f"Received on {endpoint.name}"),
            }
        )
    return prepared


def _dependencies(package: PackageSpec) -> list[str]:
    dependencies = {"rclpy"}
    for node in package.nodes:
        dependencies.update(package_name for package_name, _, _ in _interfaces(node))
    return sorted(dependencies)


def render_node(node: NodeSpec) -> str:
    imports, names = _import_plan(node)
    cls = node_class_name(node, set(names.values()))
    groups = {
        group: _prepare_endpoints(getattr(node, group), kind, names) for group, kind in _KIND_GROUPS
    }
    return _render(
        _NODE_TMPL,
        cls=cls,
        name_literal=repr(node.label),
        started_literal=repr(f"{node.label} started"),
        imports=imports,
        pubs=groups["publishers"],
        subs=groups["subscribers"],
        services=groups["services"],
        clients=groups["clients"],
        action_servers=groups["action_servers"],
        action_clients=groups["action_clients"],
        has_actions=bool(node.action_servers or node.action_clients),
    )


def render_package(package: PackageSpec) -> dict[str, str]:
    """Render every generated file of a package, keyed by POSIX path relative to it.

    Python sources are compiled before anything is written, so a template bug can never
    leave a half-written package behind.
    """
    files: dict[str, str] = {}
    for node in package.nodes:
        files[f"{package.pkg_name}/{node.label}.py"] = render_node(node)
    files[f"{package.pkg_name}/__init__.py"] = ""
    files[f"resource/{package.pkg_name}"] = ""
    files["package.xml"] = _render(
        _PKG_XML_TMPL,
        pkg_name=package.pkg_name,
        deps=_dependencies(package),
        exec_deps=["launch", "launch_ros"],
    )
    entry_points = [
        repr(f"{node.label} = {package.pkg_name}.{node.label}:main") for node in package.nodes
    ]
    files["setup.py"] = _render(
        _SETUP_PY_TMPL, pkg_literal=repr(package.pkg_name), entry_points=entry_points
    )
    files["setup.cfg"] = _SETUP_CFG.format(pkg=package.pkg_name)
    files["launch/launch.py"] = _render(
        _LAUNCH_TMPL,
        pkg_literal=repr(package.pkg_name),
        nodes=[{"literal": repr(node.label)} for node in package.nodes],
    )
    for relative, source in files.items():
        if relative.endswith(".py"):
            compile(source, relative, "exec")
    return files


def read_manifest(package_dir: Path) -> dict[str, str] | None:
    """Return {relative path: sha256} recorded at the last generation.

    ``None`` means the directory is not a generated package. Legacy (format 1) markers have
    no hashes and return an empty manifest, so every existing file is treated as user-owned.
    """
    marker = package_dir / _GENERATED_MARKER
    if not marker.is_file():
        return None
    try:
        data: object = json.loads(marker.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return {}
    if not isinstance(data, dict) or not isinstance(data.get("files"), dict):
        return {}
    return {str(k): str(v) for k, v in data["files"].items()}


def _write_atomic(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def _inside(base: Path, relative: str) -> Path:
    path = (base / relative).resolve()
    if not path.is_relative_to(base.resolve()):
        raise ValueError(f"refusing to write outside the package: {relative}")
    return path


def write_package(package: PackageSpec, output_dir: Path, files: dict[str, str]) -> GenerateResult:
    """Write rendered files without ever overwriting user edits.

    A file is (re)written only when it does not exist yet, or when its current content still
    matches the hash recorded at the previous generation. Edited files are kept and reported.
    Files the user added are never touched. Generated files that are no longer part of the
    design are removed only if unmodified.
    """
    target = output_dir / package.pkg_name
    result = GenerateResult(package=package.pkg_name)
    manifest: dict[str, str] = {}
    if target.exists():
        previous = read_manifest(target)
        if previous is None:
            raise FileExistsError(
                f"Refusing to overwrite '{target}': it was not generated by ROS 2 Inspector."
            )
        manifest = previous
    target.mkdir(parents=True, exist_ok=True)

    new_manifest: dict[str, str] = {}
    for relative, text in sorted(files.items()):
        data = text.encode("utf-8")
        new_hash = _digest(data)
        path = _inside(target, relative)
        if path.exists():
            current_hash = _digest(path.read_bytes())
            if current_hash == new_hash:
                result.unchanged.append(relative)
                new_manifest[relative] = new_hash
                continue
            if manifest.get(relative) != current_hash:
                # Edited (or pre-existing and unknown): keep the user's version.
                result.kept_modified.append(relative)
                if relative in manifest:
                    new_manifest[relative] = manifest[relative]
                continue
        _write_atomic(path, data)
        result.written.append(relative)
        new_manifest[relative] = new_hash

    for relative, old_hash in sorted(manifest.items()):
        if relative in files:
            continue
        path = _inside(target, relative)
        if not path.exists():
            continue
        if _digest(path.read_bytes()) == old_hash:
            path.unlink()
            result.removed.append(relative)
        else:
            result.kept_modified.append(relative)

    marker = {
        "generated_by": "ros2inspector",
        "format": _MARKER_FORMAT,
        "files": new_manifest,
    }
    _write_atomic(
        target / _GENERATED_MARKER,
        (json.dumps(marker, indent=2, sort_keys=True) + "\n").encode("utf-8"),
    )
    return result


def generate_package_result(
    payload: dict[str, Any] | PackageSpec, output_dir: Path
) -> GenerateResult:
    """Validate, render and write one package; report what changed on disk."""
    package = payload if isinstance(payload, PackageSpec) else PackageSpec.model_validate(payload)
    output_dir = output_dir.expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    files = render_package(package)
    return write_package(package, output_dir, files)


def generate_package(payload: dict[str, Any] | PackageSpec, output_dir: Path) -> list[str]:
    """Generate a package and return the paths (relative to ``output_dir``) that match the design.

    Existing directories are updated only when they contain the generator marker, and only
    files that the user has not modified since the last generation are replaced.
    """
    result = generate_package_result(payload, output_dir)
    return sorted(f"{result.package}/{path}" for path in result.written + result.unchanged)
