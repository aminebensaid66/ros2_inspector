def _health_class(score: int | None) -> str:
    if score is None:
        return "health-none"
    if score >= 70:
        return "health-good"
    if score >= 40:
        return "health-fair"
    return "health-poor"


def _health(score: int | None) -> str:
    return "—" if score is None else f"{score}/100"


def _md_cell(value: object) -> str:
    """Escape text for a Markdown table cell (and keep raw HTML from rendering)."""
    text = " ".join(str(value).split()).replace("&", "&amp;")
    for char in ("\\", "|", "*", "_", "`", "[", "]"):
        text = text.replace(char, "\\" + char)
    return text.replace("<", "&lt;").replace(">", "&gt;") or "—"


def _md_text(value: object) -> str:
    """Escape free text (descriptions) so it is shown, not interpreted as HTML."""
    return str(value).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").strip()


def _md_code(value: object) -> str:
    text = " ".join(str(value).split())
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    fence = "`" * (longest + 1)
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{fence}{pad}{text}{pad}{fence}"


def _ros_name(node: NodeDefinition) -> str:
    """The node's ROS name when it is known statically, else the analyser's name for it."""
    declared = node.declared_ros_name
    if declared and declared not in (DYNAMIC_SENTINEL, UNKNOWN_SENTINEL):
        return declared
    return node.name


def _names(endpoints: list[Any]) -> str:
    return ", ".join(endpoint.name for endpoint in endpoints) or "—"


def page_names(packages: list[PackageMetadata]) -> dict[str, str]:
    """Map each package path to a unique, filesystem-safe page name.

    Package names come from untrusted package.xml files, so they are never used as paths
    directly: anything outside ``[A-Za-z0-9_.-]`` is replaced and duplicates get a suffix.
    """
    pages: dict[str, str] = {}
    used: set[str] = set()
    for package in sorted(packages, key=lambda p: (p.name, p.path)):
        base = package.name if _SAFE_PAGE_RE.fullmatch(package.name) else ""
        if not base:
            base = re.sub(r"[^A-Za-z0-9_-]", "_", package.name) or "package"
        name = base
        suffix = 2
        while name.lower() in used:
            name = f"{base}-{suffix}"
            suffix += 1
        used.add(name.lower())
        pages[package.path] = name
    return pages


def _confined(base: Path, name: str) -> Path:
    path = (base / name).resolve()
    if not path.is_relative_to(base.resolve()):
        raise ValueError(f"refusing to write outside {base}: {name}")
    return path


def _write(path: Path, text: str) -> None:
    try:
        atomic_write_text(path, text)
    except OutputWriteError as exc:
        raise OSError(str(exc)) from exc


def _is_generated_page(relative: str) -> bool:
    """Only files this command can produce are ever deleted as stale."""
    parts = relative.split("/")
    if len(parts) == 1:
        return parts[0] in {"index.md", "index.html"}
    return (
        len(parts) == 2
        and parts[0] == "packages"
        and _SAFE_PAGE_RE.fullmatch(parts[1]) is not None
        and parts[1].endswith((".md", ".html"))
    )


def check_output_dir(output_dir: Path) -> None:
    """Refuse to write into a non-empty directory that holds no earlier docs run.

    Without this, ``-o docs/`` would silently replace an existing hand-written
    ``docs/index.md``.
    """
    if not output_dir.exists():
        return
    if not output_dir.is_dir():
        raise DocsOutputError(f"output path is not a directory: {output_dir}")
    if (output_dir / _MANIFEST).is_file():
        return
    if any(output_dir.iterdir()):
        raise DocsOutputError(
            f"{output_dir} is not empty and was not created by 'ros2inspector docs'. "
            "Choose another --output or pass --force to write into it."
        )


def _build_date() -> str:
    """Today's date, or SOURCE_DATE_EPOCH for reproducible builds."""
    epoch = os.environ.get("SOURCE_DATE_EPOCH", "").strip()
    if epoch.isdigit():
        return (
            datetime.datetime.fromtimestamp(int(epoch), tz=datetime.timezone.utc).date().isoformat()
        )
    return datetime.date.today().isoformat()


def _mermaid(uam: Any, graph_type: str, package: str | None = None) -> str:
    text = render_mermaid(uam, graph_type, package)
    if text.count("\n") - 1 > _MAX_DIAGRAM_NODES * 2 or text.strip() == "flowchart LR":
        return ""
    return text.replace("`", "'")


def _remove_stale(output_dir: Path, written: set[str], ext: str) -> list[str]:
    """Delete pages this command wrote last time (in this format) that are no longer produced.

    Pages of the other format are left alone and stay in the manifest, so Markdown and
    HTML docs can share one output directory.
    """
    manifest = output_dir / _MANIFEST
    try:
        previous = json.loads(manifest.read_text(encoding="utf-8")).get("files", [])
    except (OSError, ValueError, AttributeError):
        previous = []
    if not isinstance(previous, list):
        previous = []
    keep = set(written)
    removed: list[str] = []
    for relative in previous:
        if not isinstance(relative, str) or relative in written:
            continue
        if not _is_generated_page(relative):
            continue
        if not relative.endswith(f".{ext}"):
            if (output_dir / relative).is_file():
                keep.add(relative)
            continue
        try:
            path = _confined(output_dir, relative)
        except ValueError:
            continue
        if path.is_file():
            path.unlink()
            removed.append(relative)
    _write(manifest, json.dumps({"files": sorted(keep)}, indent=2) + "\n")
    return removed


def render_docs(
    uam: Any,
    root: Path,
    output_dir: Path,
    fmt: DocsFormat,
    *,
    date: str | None = None,
) -> tuple[list[str], list[str]]:
    """Write the docs; return (written files, removed stale files) relative to output_dir."""
    packages: list[PackageMetadata] = uam.packages()
    nodes: list[NodeDefinition] = uam.nodes()
    scores = {p.name: p.health_score for p in packages if p.health_score is not None}
    is_html = fmt is DocsFormat.html
    ext = "html" if is_html else "md"

    def rel(value: str) -> str:
        try:
            return Path(value).resolve().relative_to(root.resolve()).as_posix()
        except ValueError:
            return Path(value).name

    env = Environment(autoescape=is_html, keep_trailing_newline=True)
    env.globals.update(
        health_class=_health_class,
        groups=_ENDPOINT_GROUPS,
        style=Markup(_STYLE),
    )
    env.filters.update(
        health=_health,
        md=_md_cell,
        mdtext=_md_text,
        code=_md_code,
        names=_names,
        rosname=_ros_name,
        rel=rel,
    )
    page = page_names(packages)
    common: dict[str, Any] = {
        "workspace_name": root.name,
        "date": date or _build_date(),
        "distro": get_ros_distro(),
        "summary": uam.summary(),
        "packages": packages,
        "nodes": nodes,
        "page": page,
        "workspace_health": workspace_aggregate_score(scores),
    }

    output_dir.mkdir(parents=True, exist_ok=True)
    pkg_dir = output_dir / "packages"
    pkg_dir.mkdir(exist_ok=True)
    written: set[str] = set()

    index_tmpl = env.from_string(_INDEX_HTML if is_html else _INDEX_MD)
    deps = "" if is_html else _mermaid(uam, "deps")
    _write(output_dir / f"index.{ext}", index_tmpl.render(deps_diagram=deps, **common))
    written.add(f"index.{ext}")

    nodes_by_pkg: dict[str, list[NodeDefinition]] = {}
    for node in nodes:
        nodes_by_pkg.setdefault(node.package, []).append(node)
    pkg_tmpl = env.from_string(_PKG_HTML if is_html else _PKG_MD)
    for pkg in packages:
        target = _confined(pkg_dir, f"{page[pkg.path]}.{ext}")
        comms = "" if is_html else _mermaid(uam, "comms", pkg.name)
        _write(
            target,
            pkg_tmpl.render(
                pkg=pkg, pkg_nodes=nodes_by_pkg.get(pkg.name, []), comms_diagram=comms, **common
            ),
        )
        written.add(f"packages/{target.name}")

    removed = _remove_stale(output_dir, written, ext)
    return sorted(written), removed


def docs(
    path_arg: Annotated[
        Path | None, typer.Argument(metavar="[PATH]", help="Workspace root (default: CWD)")
    ] = None,
    path: Annotated[
        Path | None, typer.Option("-C", "--path", help="Workspace root (same as PATH)")
    ] = None,
    output: Annotated[
        Path | None,
        typer.Option(
            "--output",
            "-o",
            help="Output directory (default: <workspace>/ros2inspector_docs)",
        ),
    ] = None,
    fmt: Annotated[
        DocsFormat, typer.Option("--format", "-f", help="Output format")
    ] = DocsFormat.markdown,
    no_cache: Annotated[
        bool, typer.Option("--no-cache", help="Skip the incremental cache")
    ] = False,
    force: Annotated[
        bool,
        typer.Option("--force", help="Write into a non-empty directory not created by docs"),
    ] = False,
) -> None:
    """Generate architecture documentation for the workspace.

    Pages for packages that disappeared since the last run are removed. Package names
    from package.xml are sanitised before they are used as file names.

    Examples:
      ros2inspector docs
      ros2inspector docs ~/my_ws --format html -o docs/
    """
    root = find_workspace_root(pick_path(path_arg, path).resolve(), warn=not state.quiet)
    output_dir = (output.expanduser() if output else root / "ros2inspector_docs").resolve()
    if not force:
        try:
            check_output_dir(output_dir)
        except DocsOutputError as exc:
            err_console.print(f"[red]Error:[/red] {exc}")
            raise typer.Exit(2) from exc
    if not state.quiet:
        err_console.print(f"[dim]Scanning {root}…[/dim]")

    uam = build_uam_or_exit(root, use_cache=not no_cache, show_progress=not state.quiet)
    try:
        written, removed = render_docs(uam, root, output_dir, fmt)
    except (OSError, ValueError) as exc:
        err_console.print(f"[red]Error:[/red] {exc}")
        raise typer.Exit(2) from exc

    if not state.quiet:
        label = "HTML" if fmt is DocsFormat.html else "Markdown"
        err_console.print(f"[green]✓[/green] {label} docs written to [bold]{output_dir}[/bold]")
        err_console.print(f"  index:    {output_dir / written[0]}")
        err_console.print(f"  packages: {output_dir / 'packages'}/ ({len(written) - 1} files)")
        if removed:
            err_console.print(f"  removed {len(removed)} stale page(s)")
